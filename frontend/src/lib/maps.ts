/** ลิงก์ที่เก็บไว้เป็นรูปแบบ place_id — ดึงรหัสออกมาเพื่อประกอบ URL สำหรับฝัง */
const PLACE_ID = /place_id:([A-Za-z0-9_-]+)/;

export function mapEmbedUrl(mapUrl: string | null | undefined): string | null {
  const placeId = mapUrl?.match(PLACE_ID)?.[1];
  // ลิงก์รูปแบบอื่น (เช่นหมุดที่ Super Admin วางเอง) ยังกดเปิดได้ แค่ฝังในหน้าไม่ได้
  return placeId
    ? `https://www.google.com/maps/embed?origin=mfe&pb=!1m2!2m1!1splace_id:${placeId}`
    : null;
}
